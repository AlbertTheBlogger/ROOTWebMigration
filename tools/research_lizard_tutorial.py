"""Extract bounded Lizard tutorial evidence from the original install, read-only.

This utility and its extracted output are outside the current MIT file allowlist.
"""
import argparse
import hashlib
import json
from pathlib import Path
import UnityPy


ROOT = Path(__file__).resolve().parents[1]


def extract(game):
    game = game.resolve(strict=True)
    out = ROOT / 'research/lizard/tutorial'
    if game == out or game in out.parents:
        raise ValueError('Research output must be outside the original installation')
    source = game / 'Root_Data/StreamingAssets/Localization/win/localization'
    env = UnityPy.load(str(source))
    locales = {}
    for obj in env.objects:
        if obj.type.name != 'TextAsset':
            continue
        data = obj.read()
        if data.m_Name not in ('zh_CN', 'en_US'):
            continue
        raw = data.m_Script
        text = raw.decode('utf-8-sig') if isinstance(raw, bytes) else raw
        entries = {}
        for line_number, line in enumerate(text.splitlines(), 1):
            key, separator, value = line.partition('=')
            if separator and (key.startswith('lct.') or key in (
                'tutorial.title.tutorialR01', 'tutorial.description.tutorialR01',
                'tooltip.tutorial.hatedoutcast', 'tooltip.tutorial.mostcommonsuit',
            )):
                entries[key] = {'text': value, 'line': line_number}
        locales[data.m_Name] = {'textSha256': hashlib.sha256(text.encode('utf-8')).hexdigest(),
                              'pathId': obj.path_id, 'entryCount': len(entries), 'entries': entries}
    if set(locales) != {'zh_CN', 'en_US'} or any(v['entryCount'] < 40 for v in locales.values()):
        raise ValueError('Expected Lizard tutorial text was not found')
    metadata = game / 'Root_Data/il2cpp_data/Metadata/global-metadata.dat'
    index = json.loads((ROOT / 'research/baseline/metadata-index.json').read_text(encoding='utf-8'))
    types = [t for t in index['candidate_types'] if t['name'] in (
        'TuberRiverfolkTutorialGame1Script', 'TuberRiverfolkTutorialGame1SelectionFiltering', 'TutorialConstants',
    )]
    if len(types) != 3:
        raise ValueError('Regenerate the baseline metadata index for this installation')
    bundle = game / 'Root_Data/StreamingAssets/aa/StandaloneWindows64/tutorialmenuprompts_assets_all.bundle'
    env = UnityPy.load(str(bundle))
    menu = []
    for obj in env.objects:
        if obj.type.name != 'MonoBehaviour':
            continue
        try:
            tree = obj.read_typetree()
        except Exception:
            continue
        encoded = json.dumps(tree, ensure_ascii=False, default=str)
        if any(v in encoded for v in ('tutorialR01', 'OutcastInHud', 'LizardsReveals', 'GardenSetup')):
            menu.append({'pathId': obj.path_id, 'tree': tree})
    record = {
        'tool': 'tools/research_lizard_tutorial.py',
        'method': 'Fresh read-only Unity TextAsset extraction and tutorial menu scan; existing IL2CPP metadata cross-reference. No original executable run or script-body recovery.',
        'source': source.relative_to(game).as_posix(),
        'sourceSha256': hashlib.sha256(source.read_bytes()).hexdigest(), 'locales': locales,
        'metadataSourceSha256': hashlib.sha256(metadata.read_bytes()).hexdigest(), 'scriptTypes': types,
        'menuSource': bundle.relative_to(game).as_posix(),
        'menuSourceSha256': hashlib.sha256(bundle.read_bytes()).hexdigest(), 'menuMatches': menu,
        'limits': 'The current menu scan has no matching serialized string fields; script/type names do not establish original runtime progression. Existing metadata index belongs to the recorded baseline and is not regenerated by this utility.',
        'license': 'Original-game text and extracted evidence; excluded from project MIT grant.',
    }
    out.mkdir(parents=True, exist_ok=True)
    (out / 'original-evidence.json').write_text(json.dumps(record, ensure_ascii=False, indent=2, default=str) + '\n', encoding='utf-8')
    print(json.dumps({'entries': {k: v['entryCount'] for k, v in locales.items()}, 'scriptTypes': [t['name'] for t in types], 'menuMatches': len(menu)}))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('game', type=Path)
    extract(parser.parse_args().game)
